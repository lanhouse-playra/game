"""Generates GLSignatures.g.cs for the browser build.

usage: gen-gl-signatures.py <OpenGL.cs> <output .cs>

OpenRA.Platforms.Default/OpenGL.cs calls GL through delegates created with
Marshal.GetDelegateForFunctionPointer. On WebAssembly the runtime can only call a native function
pointer whose signature was seen at build time (it needs a precompiled trampoline per signature),
and the build only records signatures of [UnmanagedFunctionPointer] delegates and DllImports.
OpenGL.cs's delegates carry no attribute, so this mirrors their native signatures as attributed
delegates in OpenRA.Web. Every non-floating-point argument is pointer-sized on wasm32.
"""

import re
import sys

DELEGATE = re.compile(r"\bdelegate\s+([\w\[\]]+)\s+(\w+)\s*\(([^)]*)\)\s*;", re.S)
KEEP = {"void": "void", "float": "float", "double": "double", "long": "long", "ulong": "long"}


def native_type(managed):
    return KEEP.get(managed, "IntPtr")


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)

    source = open(sys.argv[1], encoding="utf-8-sig").read()
    signatures = {}
    for ret, name, params in DELEGATE.findall(source):
        args = []
        for param in filter(None, (p.strip() for p in params.split(","))):
            tokens = [t for t in param.split() if t not in ("ref", "out", "in")]
            args.append(native_type(tokens[-2]))

        key = (native_type(ret), tuple(args))
        signatures.setdefault(key, name)

    lines = [
        "// <auto-generated> by OpenRA.Web/tools/gen-gl-signatures.py from OpenGL.cs. Do not edit. </auto-generated>",
        "using System;",
        "using System.Runtime.InteropServices;",
        "",
        "namespace OpenRA.Web.Generated",
        "{",
        "\tstatic class GLSignatures",
        "\t{",
    ]

    for i, ((ret, args), name) in enumerate(sorted(signatures.items(), key=lambda kv: kv[1])):
        arglist = ", ".join(f"{t} a{n}" for n, t in enumerate(args))
        lines.append(f"\t\t// e.g. {name}")
        lines.append("\t\t[UnmanagedFunctionPointer(CallingConvention.Cdecl)]")
        lines.append(f"\t\tinternal delegate {ret} Signature{i}({arglist});")

    lines += ["\t}", "}", ""]
    with open(sys.argv[2], "w", encoding="utf-8") as out:
        out.write("\n".join(lines))

    print(f"{sys.argv[2]}: {len(signatures)} signatures")


if __name__ == "__main__":
    main()
